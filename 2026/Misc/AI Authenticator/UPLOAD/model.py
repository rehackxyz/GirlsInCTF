import cv2
import numpy as np
from insightface.app import FaceAnalysis

# Initialize the face recognition engine.
# The model automatically handles face detection, alignment,
# landmark extraction, and embedding generation.
app = FaceAnalysis(name="buffalo_l")

# GPU acceleration is preferred because CPU inference can be slow.
# The authentication threshold is handled internally by the model.
app.prepare(ctx_id=0)

# Pre-computed biometric template for the authorized user.
# This file contains the reference embedding generated during enrollment.
stored = np.load("my_face.npy")


def cosine_sim(a, b):
	# Normalize both feature vectors before calculating their similarity.
	# Higher values indicate that the facial features are more alike.
	return np.dot(a, b) / (np.linalg.norm(a) * np.linalg.norm(b))


def check():
	# Load the image captured from the authentication camera.
	login_img = cv2.imread("login.png")

	# Detect and analyze all faces present in the image.
	# Multiple faces are possible, so the first detected face is used.
	faces = app.get(login_img)

	if faces:
		# Extract the neural embedding generated by InsightFace.
		login_emb = faces[0].embedding

		# Compare the live embedding against the enrolled template.
		# The resulting score is used by the authentication layer.
		score = cosine_sim(stored, login_emb)

		return score

	else:
		# No detectable face means authentication cannot proceed.
		return 0